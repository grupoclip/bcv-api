// Regenerates src/mcp/schemas.ts (JSON Schemas of the stdio MCP tools) from the
// remote Worker's tools/list, so `bcv-today mcp` advertises exactly the same
// input/output schemas as https://mcp.bcv.today/mcp.
//
// Usage: (cd ../mcp && npx wrangler dev) then
//        node scripts/sync-mcp-schemas.mjs [http://127.0.0.1:8787/mcp]
import { writeFileSync } from "node:fs";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StreamableHTTPClientTransport } from "@modelcontextprotocol/sdk/client/streamableHttp.js";

const endpoint = new URL(process.argv[2] ?? "http://127.0.0.1:8787/mcp");
const client = new Client({ name: "bcv-today-schema-sync", version: "0.0.0" });
await client.connect(new StreamableHTTPClientTransport(endpoint));
const { tools } = await client.listTools();
await client.close();

const pick = (key) => Object.fromEntries(tools.map((t) => [t.name, t[key]]));
const out = `// GENERATED by scripts/sync-mcp-schemas.mjs from the Worker's tools/list. Do not edit.
// JSON Schemas of the five BCV Today MCP tools (the Worker derives them from zod).
import type { ToolName } from "./meta.js";

type JsonSchema = Record<string, unknown>;

export const INPUT_SCHEMAS: Record<ToolName, JsonSchema> = ${JSON.stringify(pick("inputSchema"), null, 2)};

export const OUTPUT_SCHEMAS: Record<ToolName, JsonSchema> = ${JSON.stringify(pick("outputSchema"), null, 2)};

export const EXECUTION: Record<ToolName, JsonSchema | undefined> = ${JSON.stringify(pick("execution"), null, 2)};
`;
const file = new URL("../src/mcp/schemas.ts", import.meta.url);
writeFileSync(file, out);
console.log(`wrote ${file.pathname} (${tools.length} tools)`);
